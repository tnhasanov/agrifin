const empty = {
  cash: 0,
  receivables: 0,
  inventory: 0,
  otherCurrentAssets: 0,
  fixedAssets: 0,
  otherLongTermAssets: 0,
  payables: 0,
  shortTermDebt: 0,
  otherCurrentLiabilities: 0,
  longTermDebt: 0,
};

/**
 * Dövr qurur. Kapital aktivlərlə öhdəliklərin fərqi kimi çıxır — nümunə
 * balanslar quruluşca bağlanır, `equity` isə mövcud olmayan bir plug deyil,
 * hesabatdan oxunmuş rəqəm kimi saxlanılır.
 */
function period(label, months, b, income, adjustments = {}) {
  const bal = { ...empty, ...b };
  const assets =
    bal.cash + bal.receivables + bal.inventory + bal.otherCurrentAssets + bal.fixedAssets + bal.otherLongTermAssets;
  const liabilities =
    bal.payables + bal.shortTermDebt + bal.otherCurrentLiabilities + bal.longTermDebt;
  return {
    label,
    months,
    audited: months === 12 && label !== "2025",
    balance: { ...bal, equity: assets - liabilities },
    income: { otherIncome: 0, ...income },
    adjustments: { unrecordedRevenue: 0, ownerAddBacks: 0, nonRecurring: 0, note: "", ...adjustments },
  };
}

