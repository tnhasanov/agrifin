// Rəqəmlər uydurmadır, amma uyğunsuz deyil: hər balans hesabatı quruluşca
// bağlanır (kapital qalıq kimi hesablanır), marjalar sahəyə uyğundur, zəif
// işlər isə qəsdən siyasət pozuntusu ilə gəlir — sistem yalnız yaxşı müştəridə
